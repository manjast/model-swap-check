"""Prompt files: parsing, the rendered developer/system message, and the Jev translation (spec §3.1, §4.1)."""

from __future__ import annotations

import hashlib
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

from swapcheck.groups import OUT_OF_SCOPE, REPO_ROOT, catalog_order

PROMPTS_DIR = REPO_ROOT / "prompts"
INCUMBENT_PROMPT = PROMPTS_DIR / "incumbent-v1.md"
JEV_PROMPT = PROMPTS_DIR / "jev-v1.yaml"
INSTRUCTION_PARTS = ("routing_instruction", "oos_clause", "output_clause")
JEV_OOS_CRITERION = "The customer message is about none of the other options."
JEV_NOUL_QUESTION = "Does the customer message ask about any of the topics in catalog?"
JEV_HEADER = "# Generated by `swapcheck prompt` from prompts/incumbent-v1.md (spec §4.1). Never edit by hand.\n"

_SECTION = re.compile(r"^## (\S+)\s*$", re.MULTILINE)
_ENTRY = re.compile(r"^### (?P<id>\S+)\n\n- description: (?P<description>[^\n]+)\n- example: (?P<example>[^\n]+)\n*\Z")


class PromptFormatError(ValueError):
    """The prompt file does not follow the format parsed here."""


@dataclass(frozen=True)
class Entry:
    intent: str
    description: str
    example: str


@dataclass(frozen=True)
class Prompt:
    routing_instruction: str
    oos_clause: str
    output_clause: str
    catalog: tuple[Entry, ...]

    @property
    def intents(self) -> list[str]:
        return [e.intent for e in self.catalog]

    @property
    def enum(self) -> list[str]:
        """The LLM output enum: the catalog IDs in catalog order, then `out_of_scope`."""
        return [*self.intents, OUT_OF_SCOPE]

    def developer_message(self) -> str:
        """The stable prefix sent as the OpenAI developer message / Anthropic system block."""
        entries = "\n\n".join(
            f"intent: {e.intent}\ndescription: {e.description}\nexample: {e.example}" for e in self.catalog
        )
        return f"{self.routing_instruction} {self.oos_clause}\n\n{self.output_clause}\n\nIntents:\n\n{entries}\n"

    def sha256(self) -> str:
        return hashlib.sha256(self.developer_message().encode()).hexdigest()


def parse_prompt(text: str) -> Prompt:
    """Parse a prompt file: `## <part>` sections for the three instruction parts and `## catalog`."""
    matches = list(_SECTION.finditer(text))
    sections: dict[str, str] = {}
    for m, nxt in zip(matches, [*matches[1:], None], strict=True):
        body = text[m.end() : nxt.start() if nxt else len(text)].strip("\n")
        sections[m.group(1)] = body
    expected = [*INSTRUCTION_PARTS, "catalog"]
    if list(sections) != expected:
        raise PromptFormatError(f"sections must be {expected}, found {list(sections)}")
    parts = {}
    for name in INSTRUCTION_PARTS:
        part = sections[name]
        if not part or "\n" in part:
            raise PromptFormatError(f"{name} must be one non-empty line")
        parts[name] = part
    entries = []
    for block in re.split(r"\n(?=### )", sections["catalog"]):
        entry = _ENTRY.match(block.strip("\n") + "\n")
        if not entry:
            raise PromptFormatError(f"malformed catalog entry:\n{block}")
        entries.append(Entry(entry["id"], entry["description"].strip(), entry["example"]))
    ids = [e.intent for e in entries]
    if ids != catalog_order(ids) or len(set(ids)) != len(ids):
        raise PromptFormatError("catalog entries must be unique and in catalog order (spec §3.1)")
    return Prompt(**parts, catalog=tuple(entries))


def load_prompt(path: Path = INCUMBENT_PROMPT) -> Prompt:
    return parse_prompt(path.read_text(encoding="utf-8"))


def jev_translation(prompt: Prompt) -> dict[str, Any]:
    """The fixed §4.1 transformation; `output_clause` is dropped because Jev output is typed."""

    def criteria() -> dict[str, Any]:
        return {e.intent: {"description": e.description, "example": e.example} for e in prompt.catalog}

    return {
        "jev-c51": {
            "choice": {
                "instructions": f"{prompt.routing_instruction} {prompt.oos_clause}",
                "criteria": {**criteria(), OUT_OF_SCOPE: JEV_OOS_CRITERION},
            },
        },
        "jev-noul": {
            "choice": {"instructions": prompt.routing_instruction, "criteria": criteria()},
            "noul": {
                "instructions": {
                    "question": JEV_NOUL_QUESTION,
                    "catalog": {e.intent: e.description for e in prompt.catalog},
                },
            },
        },
    }


def render_jev_yaml(prompt: Prompt) -> str:
    body = yaml.safe_dump(jev_translation(prompt), sort_keys=False, allow_unicode=True, width=10_000)
    return JEV_HEADER + body


def prefix_tokens(prompt: Prompt) -> int:
    """Stable-prefix length in `o200k_base` tokens (spec §3.1: must be ≥ 1,100)."""
    import tiktoken

    return len(tiktoken.get_encoding("o200k_base").encode(prompt.developer_message()))
